#!/usr/bin/env python3
"""Regenerate dashboard/src/brand/horseFrames.ts from Muybridge's plates.

Source: Eadweard Muybridge, "The Horse in Motion" (1878), public domain.
  https://commons.wikimedia.org/wiki/File:The_Horse_in_Motion.jpg

    pip install pillow numpy scipy
    curl -L -o /tmp/horse.jpg https://upload.wikimedia.org/wikipedia/commons/7/73/The_Horse_in_Motion.jpg
    python scripts/build_horse_frames.py /tmp/horse.jpg
"""
import base64
import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage as ndi

SRC = sys.argv[1] if len(sys.argv) > 1 else "horse.jpg"
OUT = Path(__file__).resolve().parents[1] / "dashboard/src/brand/horseFrames.ts"
im = np.asarray(Image.open(SRC).convert("L")).astype(float)
cols=[(25,383),(400,757),(773,1130),(1147,1505)]
rows=[(30,262),(275,503),(517,745)]
masks=[]
def top(m,x):
    ys=np.where(m[:,x])[0]; return ys[0] if len(ys) else None
for r,(y0,y1) in enumerate(rows):
    for c,(x0,x1) in enumerate(cols):
        idx=r*4+c
        if idx==11: continue
        f=im[y0+6:y1-4, x0+6:x1-6]
        m=f<85
        m=ndi.binary_opening(m, structure=np.ones((4,4)))
        # ground lines: thin vertically + long horizontally
        tall=ndi.binary_opening(m, structure=np.ones((9,1)))
        thin=m & ~tall
        longh=ndi.binary_opening(thin, structure=np.ones((1,22)))
        m=m & ~ndi.binary_dilation(longh, structure=np.ones((3,3)))
        lab,n=ndi.label(m); sizes=ndi.sum(m,lab,range(1,n+1)); m=lab==(np.argmax(sizes)+1)
        m=ndi.binary_fill_holes(m)
        xs=np.where(m.any(0))[0]; xa,xb=xs[0],xs[-1]; L=xb-xa
        # jockey: cut above line from croup to neck base
        backs=[top(m,int(xa+f*L)) for f in (0.30,0.34,0.38,0.42)]
        ya=int(np.median([b for b in backs if b is not None]))
        for x in range(int(xa+0.44*L), int(xa+0.755*L)):
            t=(x-(xa+0.44*L))/(0.315*L)
            yl=ya+1-int(6*max(0,t-0.6)/0.4)  # let the withers rise slightly
            m[:yl,x]=False
        yy,xx=np.mgrid[-7:8,-7:8]; disk=(yy**2+xx**2)<=49
        sm=ndi.binary_opening(m, structure=disk)
        a,b=int(xa+0.66*L),int(xa+0.86*L)
        band=np.zeros_like(m); band[:ya+8,a:b]=True
        m=np.where(band, sm, m)
        m=ndi.binary_opening(m, structure=np.ones((3,3)))
        lab,n=ndi.label(m); sizes=ndi.sum(m,lab,range(1,n+1)); m=lab==(np.argmax(sizes)+1)
        masks.append(m)
H = max(m.shape[0] for m in masks)
W = max(m.shape[1] for m in masks)
masks = [np.pad(m, ((0, H - m.shape[0]), (0, W - m.shape[1]))) for m in masks]

# --------------------------------------------------------------------------- #
# Align on centre of mass, downsample to the glyph grid, pack 1-bit.
# --------------------------------------------------------------------------- #
cms = [ndi.center_of_mass(m) for m in masks]
cy = np.mean([c[0] for c in cms])
cx = np.mean([c[1] for c in cms])
al = [ndi.shift(m.astype(float), (cy - y, cx - x), order=0) > 0.5 for m, (y, x) in zip(masks, cms)]
u = np.any(al, 0)
ys = np.where(u.any(1))[0]
xs = np.where(u.any(0))[0]
y0, y1 = max(ys[0] - 4, 0), ys[-1] + 4
x0, x1 = max(xs[0] - 4, 0), xs[-1] + 4
h, w = y1 - y0, x1 - x0
COLS = 132
ROWS = int(round(COLS * h / w * 0.62))  # glyph cells are taller than wide

frames = []
for m in al:
    c = (m[y0:y1, x0:x1] * 255).astype(np.uint8)
    small = np.asarray(Image.fromarray(c).resize((COLS, ROWS), Image.BOX)) > 110
    frames.append(base64.b64encode(np.packbits(small.flatten()).tobytes()).decode())

# Logo: the fully-extended stride (frame 7), as a pixel-art SVG path.
LW = 32
LH = int(round(LW * h / w))
src = (al[6][y0:y1, x0:x1] * 255).astype(np.uint8)
logo = np.asarray(Image.fromarray(src).resize((LW, LH), Image.BOX)) > 64
rects = []
for yy in range(LH):
    xx = 0
    while xx < LW:
        if logo[yy, xx]:
            s = xx
            while xx < LW and logo[yy, xx]:
                xx += 1
            rects.append(f"M{s} {yy}h{xx - s}v1h-{xx - s}z")
        else:
            xx += 1

frame_lines = "\n".join(f'  "{f}",' for f in frames)
OUT.write_text(f'''/**
 * Gallop frames for the brand horse.
 *
 * Derived from Eadweard Muybridge, "The Horse in Motion" (1878) -- public
 * domain. The 11 gallop plates were thresholded to silhouettes, the rider and
 * track lines removed, aligned on centre of mass and packed as 1-bit bitmaps
 * ({COLS}x{ROWS} cells, row-major, MSB first, base64).
 *
 * GENERATED by scripts/build_horse_frames.py -- do not edit by hand.
 */
export const HORSE_COLS = {COLS};
export const HORSE_ROWS = {ROWS};
export const HORSE_FRAMES: readonly string[] = [
{frame_lines}
];

/** 1-bit pixel horse ({LW}x{LH}) as one SVG path, for the logo mark. */
export const HORSE_MARK_W = {LW};
export const HORSE_MARK_H = {LH};
export const HORSE_MARK_PATH =
  "{"".join(rects)}";

/** Decode one frame into a Uint8Array of 0/1 cells. */
export function decodeFrame(b64: string): Uint8Array {{
  const bin = atob(b64);
  const out = new Uint8Array(HORSE_COLS * HORSE_ROWS);
  for (let i = 0; i < out.length; i++) {{
    out[i] = (bin.charCodeAt(i >> 3) >> (7 - (i & 7))) & 1;
  }}
  return out;
}}
''')
print(f"wrote {OUT} ({COLS}x{ROWS}, {len(frames)} frames, logo {LW}x{LH})")
print("\n".join("".join("#" if v else "." for v in row) for row in logo))
