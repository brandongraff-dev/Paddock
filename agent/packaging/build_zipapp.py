#!/usr/bin/env python3
"""Build ``paddock-agent.pyz``: the agent as one deterministic, stdlib-only zipapp (docs/ASSURANCE_P2.md E7).

    python agent/packaging/build_zipapp.py --out dist/paddock-agent.pyz [--sums dist/SHA256SUMS]

* Only ``paddock_agent/**/*.py`` goes in (no tests, fixtures, docs or bytecode) plus a generated
  ``__main__.py`` that does ``sys.exit(main())``. ``zipapp``'s own ``main=`` shortcut drops the return
  value, which would turn exit status 7 ("the server requires re-enrollment", see
  ``RestartPreventExitStatus=7``) into 0, so the entry point is written out explicitly.
* **Reproducible**: the same sources give the same bytes, whatever the build time, time zone, umask,
  checkout location or Python version (3.8 to 3.13 give identical archives, which ``zipapp``'s own
  directory mode does not: it changed in 3.12). The zip is therefore written member by member with an
  explicit ``ZipInfo`` (one fixed timestamp, ``SOURCE_DATE_EPOCH`` or 1980-01-01; fixed modes; sorted;
  files only; no compression, because a deflate stream depends on the zlib build) and ``zipapp`` only
  puts the interpreter line in front of that archive.
* Python >= 3.8, standard library only, so the same script runs in the ``python:3.8`` CI job.

The shebang is ``#!/usr/bin/env python3``; the installer runs the archive with an explicit interpreter
that it checked to be >= 3.8 instead of trusting the shebang.
"""
import argparse
import hashlib
import io
import os
import sys
import time
import zipapp
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
AGENT_DIR = os.path.dirname(HERE)
PACKAGE = "paddock_agent"
ZIP_EPOCH_MIN = 315532800          # 1980-01-01T00:00:00Z: the earliest instant a zip member can carry
DEFAULT_EPOCH = ZIP_EPOCH_MIN
INTERPRETER = "/usr/bin/env python3"
MAIN_PY = (
    "# generated by agent/packaging/build_zipapp.py; do not edit\n"
    "import sys\n"
    "\n"
    "from paddock_agent.cli import main\n"
    "\n"
    "sys.exit(main())\n"
)
APP_NAME = "paddock-agent.pyz"


class BuildError(RuntimeError):
    pass


def source_date_epoch(value=None):
    raw = value if value is not None else os.environ.get("SOURCE_DATE_EPOCH")
    if raw in (None, ""):
        return DEFAULT_EPOCH
    try:
        epoch = int(str(raw))
    except ValueError:
        raise BuildError("SOURCE_DATE_EPOCH must be an integer, got %r" % (raw,))
    if epoch < ZIP_EPOCH_MIN:
        raise BuildError("SOURCE_DATE_EPOCH %d is before 1980-01-01, which a zip cannot store" % epoch)
    return epoch


def package_files(agent_dir=AGENT_DIR):
    """Sorted ``(relative_posix_path, absolute_path)`` for every module that belongs in the archive."""
    root = os.path.join(agent_dir, PACKAGE)
    if not os.path.isfile(os.path.join(root, "__init__.py")):
        raise BuildError("%s is not the agent source tree (no %s/__init__.py)" % (agent_dir, PACKAGE))
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d != "__pycache__" and not d.startswith("."))
        for name in sorted(filenames):
            if not name.endswith(".py"):
                continue
            full = os.path.join(dirpath, name)
            if os.path.islink(full):
                raise BuildError("refusing to package a symlink: %s" % full)
            rel = os.path.relpath(full, agent_dir).replace(os.sep, "/")
            found.append((rel, full))
    return sorted(found)


def members(agent_dir=AGENT_DIR):
    """``[(archive name, bytes)]`` in archive order: ``__main__.py`` first, then the package, sorted."""
    out = [("__main__.py", MAIN_PY.encode("utf-8"))]
    for rel, full in package_files(agent_dir):
        with open(full, "rb") as fh:
            out.append((rel, fh.read().replace(b"\r\n", b"\n")))
    return out


def zip_bytes(epoch, agent_dir=AGENT_DIR):
    """The archive itself, byte-identical for identical inputs on any platform and Python 3.8+."""
    date_time = time.gmtime(epoch)[:6]
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_STORED) as zf:
        for name, data in members(agent_dir):
            info = zipfile.ZipInfo(name, date_time)
            info.compress_type = zipfile.ZIP_STORED
            info.create_system = 3                       # unix, whatever the builder runs on
            info.external_attr = (0o100644 << 16)        # -rw-r--r--
            zf.writestr(info, data)
    return buf.getvalue()


def build(out, *, epoch=None, agent_dir=AGENT_DIR):
    """Write the archive to ``out`` (atomically) and return its sha256 hex digest."""
    epoch = source_date_epoch(epoch)
    out = os.path.abspath(out)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    tmp_out = out + ".tmp-%d" % os.getpid()
    try:
        zipapp.create_archive(io.BytesIO(zip_bytes(epoch, agent_dir)), tmp_out, interpreter=INTERPRETER)
        os.chmod(tmp_out, 0o755)
        os.replace(tmp_out, out)
    finally:
        if os.path.exists(tmp_out):
            os.unlink(tmp_out)
    return sha256_file(out)


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def write_sums(sums_path, entries):
    """``sha256sum``-format manifest (two spaces, binary-agnostic), sorted by name."""
    with open(sums_path, "w", encoding="utf-8", newline="\n") as fh:
        for name, digest in sorted(entries):
            fh.write("%s  %s\n" % (digest, name))


def main(argv=None):
    ap = argparse.ArgumentParser(description="Build the deterministic paddock-agent.pyz zipapp.")
    ap.add_argument("--out", default=os.path.join("dist", APP_NAME), help="output path (default dist/%s)" % APP_NAME)
    ap.add_argument("--sums", help="also write a sha256sum-format manifest to this path")
    ap.add_argument("--also", action="append", default=[], metavar="FILE",
                    help="add FILE (e.g. scripts/install-agent.sh) to the --sums manifest under its base name")
    ap.add_argument("--source-date-epoch", help="member timestamp (default $SOURCE_DATE_EPOCH, else 1980-01-01)")
    args = ap.parse_args(argv)
    try:
        digest = build(args.out, epoch=args.source_date_epoch)
        if args.sums:
            entries = [(os.path.basename(args.out), digest)]
            for extra in args.also:
                entries.append((os.path.basename(extra), sha256_file(extra)))
            write_sums(args.sums, entries)
    except (BuildError, OSError) as exc:
        print("error: %s" % exc, file=sys.stderr)
        return 1
    print("%s  %s" % (digest, os.path.basename(args.out)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
