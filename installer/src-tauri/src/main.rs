//! Paddock Setup: a wizard around `scripts/install.ps1`.
//!
//! This file is deliberately thin. What may run, with which arguments, and which pages may be
//! opened is decided (and tested) in `../core`. Here we only: unpack the bundled installer files,
//! start PowerShell, forward its output lines to the wizard, and stop it on cancel or close.
//! The wizard (../ui) turns those lines into screens.

#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

use std::collections::HashMap;
use std::fs;
use std::io::{BufRead, BufReader, Read};
#[cfg(windows)]
use std::os::windows::process::CommandExt;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::{Arc, Mutex};

use paddock_installer_core as core;
use serde::Serialize;
use tauri::{AppHandle, Emitter, Manager, State};

// `EMBEDDED: &[(&str, &[u8])]`, generated by build.rs from ../resources
include!(concat!(env!("OUT_DIR"), "/embedded.rs"));

const APP_VERSION: &str = env!("CARGO_PKG_VERSION");
const PADDOCK_PORT: u16 = 3000;
/// CREATE_NO_WINDOW: no console flashes up when we start PowerShell.
#[cfg(windows)]
const NO_WINDOW: u32 = 0x0800_0000;

/// run id -> process id of the PowerShell that run started.
#[derive(Default)]
struct Runs(Arc<Mutex<HashMap<String, u32>>>);

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct AppState {
    installed: bool,
    version: Option<String>,
    running: bool,
    dir: String,
    resources_ready: bool,
    app_version: String,
}

#[derive(Serialize, Clone)]
struct LineEvent {
    run_id: String,
    line: String,
}

// ---------------------------------------------------------------------------
// where things live
// ---------------------------------------------------------------------------

fn user_profile() -> String {
    std::env::var("USERPROFILE")
        .or_else(|_| std::env::var("HOME"))
        .unwrap_or_default()
}

/// Per-user (never shared) scratch space for Setup.
fn data_dir() -> PathBuf {
    let base = std::env::var_os("LOCALAPPDATA")
        .map(PathBuf::from)
        .unwrap_or_else(std::env::temp_dir);
    base.join("Paddock").join("setup")
}

fn last_dir_file() -> PathBuf {
    data_dir().join("last-dir.txt")
}

/// The folder chosen last time. Re-validated: a file on disk is not trusted.
fn remembered_dir() -> Option<String> {
    let s = fs::read_to_string(last_dir_file()).ok()?;
    core::validate_dir(s.trim()).ok()
}

fn remember_dir(dir: Option<&str>) {
    if let Some(Ok(clean)) = dir.map(core::validate_dir) {
        let _ = fs::create_dir_all(data_dir());
        let _ = fs::write(last_dir_file(), clean);
    }
}

fn chosen_dir() -> String {
    remembered_dir().unwrap_or_else(|| core::default_dir(&user_profile()))
}

/// Absolute path of a Windows system tool, so a poisoned PATH cannot swap it.
fn system32(exe: &str) -> PathBuf {
    match std::env::var_os("SystemRoot") {
        Some(root) => PathBuf::from(root).join("System32").join(exe),
        None => PathBuf::from(exe),
    }
}

fn powershell() -> PathBuf {
    let p = system32("WindowsPowerShell\\v1.0\\powershell.exe");
    if p.is_file() {
        p
    } else if cfg!(windows) {
        PathBuf::from("powershell.exe")
    } else {
        PathBuf::from("pwsh") // developing on macOS/Linux
    }
}

// ---------------------------------------------------------------------------
// the bundled installer files
// ---------------------------------------------------------------------------

fn fnv1a(data: &[u8], mut h: u64) -> u64 {
    for b in data {
        h ^= u64::from(*b);
        h = h.wrapping_mul(0x0000_0100_0000_01b3);
    }
    h
}

/// Write the embedded files to a per-user folder and return the path of `install.ps1`.
/// Rewritten on every run: nothing already on disk is trusted.
fn extract_resources() -> Result<PathBuf, String> {
    if EMBEDDED.is_empty() {
        return Err(
            "This copy of Paddock Setup is incomplete: the installer files are missing.".into(),
        );
    }
    let mut h = 0xcbf2_9ce4_8422_2325_u64;
    for &(name, bytes) in EMBEDDED.iter() {
        h = fnv1a(name.as_bytes(), h);
        h = fnv1a(bytes, h);
    }
    let base = data_dir();
    let root = base.join(format!("files-{h:016x}"));
    for &(name, bytes) in EMBEDDED.iter() {
        if name.split('/').any(|p| p.is_empty() || p == "..") {
            return Err("Unexpected file name inside Paddock Setup.".into());
        }
        let dest = root.join(name);
        if let Some(parent) = dest.parent() {
            fs::create_dir_all(parent)
                .map_err(|e| format!("Could not prepare {}: {e}", parent.display()))?;
        }
        fs::write(&dest, bytes).map_err(|e| format!("Could not write {}: {e}", dest.display()))?;
    }
    // tidy up older unpacked copies (best effort)
    if let Ok(entries) = fs::read_dir(&base) {
        for e in entries.flatten() {
            let p = e.path();
            if p != root
                && p.file_name()
                    .is_some_and(|n| n.to_string_lossy().starts_with("files-"))
            {
                let _ = fs::remove_dir_all(p);
            }
        }
    }
    Ok(root.join("install.ps1"))
}

