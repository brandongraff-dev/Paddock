/// The Paddock release this Setup installs ("dev" for a from-source build), from the bundled VERSION file.
fn embedded_version() -> String {
    EMBEDDED
        .iter()
        .find(|(name, _)| *name == "VERSION")
        .and_then(|(_, bytes)| std::str::from_utf8(bytes).ok())
        .map(|s| s.trim().to_string())
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| APP_VERSION.to_string())
}

#[tauri::command]
fn get_state() -> AppState {
    let dir = chosen_dir();
    let info = core::detect_install(Path::new(&dir));
    AppState {
        installed: info.installed,
        version: info.version,
        running: info.installed && core::port_open(PADDOCK_PORT),
        dir,
        resources_ready: !EMBEDDED.is_empty(),
        app_version: embedded_version(),
    }
}

/// Forward every line of a child's output to the wizard.
fn pump<R: Read>(app: &AppHandle, run_id: &str, reader: R) {
    let mut rd = BufReader::new(reader);
    let mut buf = Vec::new();
    loop {
        buf.clear();
        match rd.read_until(b'\n', &mut buf) {
            Ok(0) | Err(_) => break,
            Ok(_) => {}
        }
        let line = core::clean_line(&String::from_utf8_lossy(&buf));
        if line.trim().is_empty() {
            continue;
        }
        let _ = app.emit(
            "installer-line",
            LineEvent {
                run_id: run_id.to_string(),
                line,
            },
        );
    }
}

fn run_blocking(
    app: AppHandle,
    table: Arc<Mutex<HashMap<String, u32>>>,
    run_id: String,
    opts: core::Options,
) -> Result<i32, String> {
    let script = extract_resources()?;
    let args = core::build_args(&script.to_string_lossy(), &opts).map_err(|e| e.to_string())?;

    let mut cmd = Command::new(powershell());
    cmd.args(&args)
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());
    #[cfg(windows)]
    cmd.creation_flags(NO_WINDOW);
    let mut child = cmd
        .spawn()
        .map_err(|e| format!("PowerShell could not be started: {e}"))?;

    table
        .lock()
        .map_err(|_| "internal error".to_string())?
        .insert(run_id.clone(), child.id());
    let stdout = child.stdout.take();
    let stderr = child.stderr.take();
    let (app2, id2) = (app.clone(), run_id.clone());
    let errors = std::thread::spawn(move || {
        if let Some(s) = stderr {
            pump(&app2, &id2, s);
        }
    });
    if let Some(s) = stdout {
        pump(&app, &run_id, s);
    }
    let _ = errors.join();
    let status = child.wait().map_err(|e| e.to_string())?;
    if let Ok(mut t) = table.lock() {
        t.remove(&run_id);
    }
    let code = status.code().unwrap_or(-1);
    if code == 0 && opts.action == core::Action::Install {
        remember_dir(opts.dir.as_deref());
    }
    Ok(code)
}

/// Run one installer action. Resolves with the script's exit code; the lines it prints arrive as
/// `installer-line` events while it runs.
#[tauri::command]
async fn run_script(
    app: AppHandle,
    runs: State<'_, Runs>,
    run_id: String,
    action: String,
    dir: Option<String>,
    active: bool,
) -> Result<i32, String> {
    let action = core::Action::parse(&action).ok_or_else(|| "Unknown action.".to_string())?;
    let opts = core::Options {
        action,
        dir,
        active,
    };
    let table = runs.0.clone();
    let result =
        tauri::async_runtime::spawn_blocking(move || run_blocking(app, table, run_id, opts))
            .await
            .map_err(|e| e.to_string())?;
    result
}

fn kill_tree(pid: u32) {
    #[cfg(windows)]
    {
        let _ = Command::new(system32("taskkill.exe"))
            .args(["/PID", &pid.to_string(), "/T", "/F"])
            .creation_flags(NO_WINDOW)
            .status();
    }
    #[cfg(not(windows))]
    {
        let _ = Command::new("kill")
            .args(["-TERM", &pid.to_string()])
            .status();
    }
}

fn kill_all(runs: &Runs) {
    if let Ok(mut t) = runs.0.lock() {
        for (_, pid) in t.drain() {
            kill_tree(pid);
        }
    }
}

#[tauri::command]
fn cancel_run(runs: State<'_, Runs>, run_id: String) {
    let pid = runs.0.lock().ok().and_then(|t| t.get(&run_id).copied());
    if let Some(pid) = pid {
        kill_tree(pid);
    }
}

#[tauri::command]
fn open_url(url: String) -> Result<(), String> {
    if !core::allowed_url(&url) {
        return Err("That address is not allowed.".into());
    }
    #[cfg(windows)]
    let spawned = Command::new(system32("rundll32.exe"))
        .args(["url.dll,FileProtocolHandler", &url])
        .creation_flags(NO_WINDOW)
        .spawn();
    #[cfg(target_os = "macos")]
    let spawned = Command::new("open").arg(&url).spawn();
    #[cfg(all(not(windows), not(target_os = "macos")))]
    let spawned = Command::new("xdg-open").arg(&url).spawn();
    spawned
        .map(|_| ())
        .map_err(|e| format!("Could not open the browser: {e}"))
}

#[tauri::command]
fn quit_app(app: AppHandle, runs: State<'_, Runs>) {
    kill_all(&runs);
    app.exit(0);
}

fn main() {
    tauri::Builder::default()
        .manage(Runs::default())
        .invoke_handler(tauri::generate_handler![
            get_state, run_script, cancel_run, open_url, quit_app
        ])
        .on_window_event(|window, event| {
            // closing the window must not leave an install running in the background
            if let tauri::WindowEvent::CloseRequested { .. } = event {
                kill_all(&window.state::<Runs>());
            }
        })
        .run(tauri::generate_context!())
        .expect("error while running Paddock Setup");
}
