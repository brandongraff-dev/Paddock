"""`paddock fix --pr`: propose the fixes as a GitHub pull request.

Guarantees, enforced here and covered by tests:
* the work happens on a NEW branch named ``paddock/fix-...``; the push refspec is
  ``HEAD:refs/heads/<that branch>``, so the default branch can never be the target;
* the pull request is only ever *opened*; there is no merge and no auto-merge call;
* the token comes from ``GITHUB_TOKEN`` (never a flag, never logged, passed to git
  through the environment rather than the argument list);
* the PR text is scanned with the remediation service's injection scanner before it is sent.
"""
from __future__ import annotations

import base64
import hashlib
import json
import os
import re
import subprocess
import time
import urllib.error
import urllib.request
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable

from . import __version__, engines
from .applyfix import Verification, apply_plans
from .fixplan import FixPlan, combined_edits

Api = Callable[[str, str, dict[str, Any] | None], Any]
BRANCH_PREFIX = "paddock/"


class PrError(RuntimeError):
    pass


@dataclass
class PrResult:
    url: str
    number: int | None
    branch: str
    base: str
    files: list[str]


def _git(root: Path, *args: str, env: dict[str, str] | None = None, check: bool = True) -> str:
    cmd = ["git", "-C", str(root), *args]
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=120,
                           env={**os.environ, **(env or {})})
    except (OSError, subprocess.SubprocessError) as exc:
        raise PrError(f"git failed to run: {exc}") from exc
    if check and p.returncode != 0:
        raise PrError(f"git {args[0]} failed: {(p.stderr or p.stdout).strip()[:300]}")
    return p.stdout.strip()


def parse_repo(url: str) -> str | None:
    m = re.search(r"github\.com[:/]+([\w.\-]+)/([\w.\-]+?)(?:\.git)?/?$", url.strip())
    return f"{m.group(1)}/{m.group(2)}" if m else None


def github_api(token: str, base_url: str | None = None) -> Api:
    base = (base_url or os.environ.get("PADDOCK_GITHUB_API") or "https://api.github.com").rstrip("/")

    def call(method: str, path: str, body: dict[str, Any] | None = None) -> Any:
        req = urllib.request.Request(
            base + path, method=method, data=json.dumps(body).encode() if body is not None else None,
            headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json",
                     "X-GitHub-Api-Version": "2022-11-28", "Content-Type": "application/json",
                     "User-Agent": f"paddock-cli/{__version__}"})
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:  # noqa: S310 - https
                return json.loads(resp.read().decode() or "null")
        except urllib.error.HTTPError as exc:
            detail = exc.read().decode("utf-8", "replace")[:300]
            raise PrError(f"GitHub API {method} {path} -> HTTP {exc.code}: {detail}") from exc
        except (urllib.error.URLError, TimeoutError) as exc:
            raise PrError(f"GitHub API unreachable: {exc}") from exc
    return call


def build_pr_text(plans: list[FixPlan], ver: Verification | None, *,
                  summaries: bool = True) -> tuple[str, str]:
    n = len(plans)
    title = (f"paddock: {plans[0].title}" if n == 1
             else f"paddock: fix {n} security findings")
    out = ["## Paddock automated fixes", "",
           "Proposed by `paddock fix`. Every change is generated deterministically (no model "
           "writes code) and passed a safety gate before it was offered. **Nothing here is "
           "merged automatically; please review the diff.**", ""]
    for i, p in enumerate(plans, 1):
        out.append(f"### {i}. {p.title}")
        if p.detail.get("osv_ids"):
            out.append(f"- Advisories: {', '.join(p.detail['osv_ids'][:6])}")
        out.append(f"- Files: {', '.join(f'`{e.path}`' for e in p.edits)}")
        if summaries and p.why:
            out.append(f"- Why it matters: {p.why}")
        out.append(f"- Safety gate: {'passed' if p.gate_ok else 'FAILED'} ({p.gate_engine})")
        for note in p.notes:
            out.append(f"- Note: {note}")
        out.append("")
    if ver is not None:
        out.append("### Verification")
        out.append(f"After applying, the checks were re-run: **verified {ver.fixed} of {ver.total} fixed**.")
        for o in ver.outcomes:
            if o.status != "fixed":
                out.append(f"- {o.plan.title}: {o.status.replace('_', ' ')} ({o.reason})")
        out.append("")
    out.append("<sub>Generated by paddock-cli " + __version__ + "</sub>")
    return title, "\n".join(out)


def open_pr(root: str | Path, plans: list[FixPlan], ver_fn: Callable[[], Verification | None],
            *, token: str, repo: str | None = None, draft: bool = False,
            api: Api | None = None, remote: str = "origin") -> PrResult:
    """Branch, apply, verify, commit, push and open the PR; then return to the old branch."""
    root = Path(root).resolve()
    if not token:
        raise PrError("GITHUB_TOKEN is not set (needs `contents: write` and `pull_requests: write`)")
    if not plans:
        raise PrError("nothing to commit")
    if _git(root, "rev-parse", "--is-inside-work-tree", check=False) != "true":
        raise PrError("not inside a git repository")
    url = _git(root, "remote", "get-url", remote, check=False)
    repo = repo or os.environ.get("GITHUB_REPOSITORY") or parse_repo(url)
    if not repo or "/" not in repo:
        raise PrError("could not work out the GitHub repository; pass --repo OWNER/NAME")
    api = api or github_api(token)

    base = None
    try:
        base = (api("GET", f"/repos/{repo}", None) or {}).get("default_branch")
    except PrError:
        pass
    if not base:
        head = _git(root, "symbolic-ref", "--short", f"refs/remotes/{remote}/HEAD", check=False)
        base = head.split("/", 1)[1] if "/" in head else _git(root, "rev-parse", "--abbrev-ref", "HEAD")

    files = sorted(combined_edits(plans))
    dirty = _git(root, "status", "--porcelain", "--", *files, check=False)
    if dirty:
        raise PrError("these files have uncommitted changes; commit or stash them first:\n" + dirty)

    orig = _git(root, "rev-parse", "--abbrev-ref", "HEAD")
    if orig == "HEAD":
        orig = _git(root, "rev-parse", "HEAD")
    digest = hashlib.sha256("".join(sorted(p.id for p in plans)).encode()).hexdigest()[:7]
    branch = f"{BRANCH_PREFIX}fix-{time.strftime('%Y%m%d')}-{digest}"
    if branch == base or not branch.startswith(BRANCH_PREFIX):  # belt and braces
        raise PrError("refusing to use the default branch")
    if _git(root, "rev-parse", "--verify", "--quiet", f"refs/heads/{branch}", check=False):
        branch += f"-{int(time.time()) % 10000}"

    _git(root, "switch", "-c", branch)
    try:
        apply_plans(plans, root)
        ver = ver_fn()
        _git(root, "add", "--", *files)
        title, body = build_pr_text(plans, ver)
        scan = engines.injection().scan_fields({"pr_title": title, "pr_body": body})
        if scan["blocked"]:  # third-party advisory text tripped the scanner: drop it
            title, body = build_pr_text(plans, ver, summaries=False)
            scan = engines.injection().scan_fields({"pr_title": title, "pr_body": body})
            if scan["blocked"]:
                raise PrError("PR text was flagged by the injection scanner: " + scan["summary"])
        ident = []
        if not _git(root, "config", "user.email", check=False):
            ident = ["-c", "user.name=paddock-cli", "-c", "user.email=paddock-cli@users.noreply.github.com"]
        _git(root, *ident, "commit", "-m", title, "-m", body.split("### Verification")[0][:2000])
        auth = base64.b64encode(f"x-access-token:{token}".encode()).decode()
        env = {"GIT_CONFIG_COUNT": "1", "GIT_CONFIG_KEY_0": "http.https://github.com/.extraheader",
               "GIT_CONFIG_VALUE_0": f"AUTHORIZATION: basic {auth}", "GIT_TERMINAL_PROMPT": "0"}
        _git(root, "push", remote, f"HEAD:refs/heads/{branch}", env=env)
        pr = api("POST", f"/repos/{repo}/pulls",
                 {"title": title, "head": branch, "base": base, "body": body, "draft": draft})
    except BaseException:
        # Put our files back so the working tree is exactly as we found it.
        _git(root, "reset", "--quiet", "HEAD", "--", *files, check=False)
        for path, (before, _after) in combined_edits(plans).items():
            if before is None:
                (root / path).unlink(missing_ok=True)
            else:
                _git(root, "checkout", "--quiet", "HEAD", "--", path, check=False)
        raise
    finally:
        _git(root, "switch", "--quiet", orig, check=False)
    return PrResult(url=str((pr or {}).get("html_url") or ""), number=(pr or {}).get("number"),
                    branch=branch, base=base, files=files)
