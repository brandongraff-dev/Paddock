"""Generated catalogue documents (contract 3.2): CHECKS.md (static columns) and TIERS.md (effective tiers).

``render_checks_md`` contains only facts that do not depend on measurement, so it never goes stale
when ``tiers.json`` changes. ``render_tiers_md`` shows the effective tier and evidence label of
every check and how many checks are default-on. ``pack_counts`` feeds ``test_catalogue_counts``.
"""
from __future__ import annotations

from typing import Iterable

from paddock_cli.guard import model, registry, textsafe
from paddock_cli.guard.registry import Check

# 4.10: declared counts per pack at the contract date (checks, high, medium, low).
EXPECTED_COUNTS: dict[str, tuple[int, int, int, int]] = {
    "SEC": (11, 10, 1, 0), "BAAS": (7, 5, 2, 0), "WEB": (12, 6, 6, 0), "AGT": (6, 3, 3, 0),
    "SUP": (5, 5, 0, 0), "CI": (4, 4, 0, 0), "DKR": (4, 4, 0, 0), "PKG": (7, 3, 2, 2), "URL": (4, 1, 2, 1),
}
EXPECTED_TOTAL = (60, 41, 16, 3)


def _cell(v: object, cap: int = 300) -> str:
    t = textsafe.cap(textsafe.collapse_ws(textsafe.clean(v if isinstance(v, str) else str(v))), cap)
    return t.replace("|", "\\|")


def pack_counts(checks: Iterable[Check]) -> dict[str, tuple[int, int, int, int]]:
    """Declared counts per built-in pack: (checks, high, medium, low)."""
    out: dict[str, list[int]] = {}
    for c in checks:
        if c.origin != "builtin":
            continue
        row = out.setdefault(c.pack, [0, 0, 0, 0])
        row[0] += 1
        row[{"high": 1, "medium": 2, "low": 3}[c.proposed_tier]] += 1
    return {k: tuple(v) for k, v in sorted(out.items())}  # type: ignore[misc]


def render_checks_md(checks: Iterable[Check]) -> str:
    rows = sorted(checks, key=lambda c: c.id)
    lines = [
        "# Paddock Guard check catalogue",
        "",
        "Generated by `paddock guard catalogue`; do not edit by hand. Static columns only: the effective tier of each",
        "check is in `TIERS.md`. The rationale column is anecdotal unless it carries a source.",
        "",
        "| ID | Title | Severity | Declared tier | Scope | CWE | Fixer | Inline suppressible | Spec status | Why |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for c in rows:
        lines.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            _cell(c.id, 40), _cell(c.title, 120), c.severity, c.proposed_tier, c.scope, _cell(c.cwe or "-", 20),
            _cell(c.fixer or "-", 40), "yes" if c.inline_suppressible else "no", c.spec_status,
            _cell(registry.why_text(c), 400)))
    lines += ["", "%d checks." % len(rows), ""]
    return "\n".join(lines)


def render_tiers_md(checks: Iterable[Check]) -> str:
    rows = sorted(checks, key=lambda c: c.id)
    lines = [
        "# Paddock Guard effective tiers",
        "",
        "Generated by `paddock guard catalogue`; do not edit by hand. The effective tier comes from `data/tiers.json`",
        "when it has an entry for the check, otherwise from the declared proposal (labelled `unmeasured`).",
        "A release build without a `tiers.json` entry treats a check as `medium` (decision D8).",
        "",
        "| ID | Declared tier | Effective tier | Evidence | Open UNVERIFIED ids |",
        "| --- | --- | --- | --- | --- |",
    ]
    n_high = 0
    for c in rows:
        eff, label = registry.effective_tier(c)
        n_high += eff == "high"
        lines.append("| %s | %s | %s | %s | %s |" % (
            _cell(c.id, 40), c.proposed_tier, eff, label, _cell(", ".join(registry.open_unverified(c)) or "-", 80)))
    lines += ["", "%d of %d checks are effective-high (default-on and able to block)." % (n_high, len(rows)),
              "Release build requires measured tiers: %s." % ("yes" if model.REQUIRE_TIERS else "no"), ""]
    return "\n".join(lines)
